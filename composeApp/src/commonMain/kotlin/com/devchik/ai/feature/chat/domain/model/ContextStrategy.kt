package com.devchik.ai.feature.chat.domain.model

/**
 * Перечисление доступных стратегий управления контекстом диалога.
 *
 * Каждая стратегия определяет, как обрабатывается история сообщений
 * перед отправкой в LLM — баланс между полнотой контекста и лимитом токенов.
 *
 * @property displayName Имя стратегии для отображения в UI настроек.
 * @property description Краткое описание стратегии на русском языке для UI.
 */
enum class ContextStrategy(val displayName: String, val description: String) {

    /**
     * Простейшая стратегия — скользящее окно.
     * Хранит только последние N сообщений, всё остальное отбрасывается безвозвратно.
     * Минимальное потребление токенов, но полная потеря раннего контекста.
     */
    SLIDING_WINDOW(
        displayName = "Sliding Window",
        description = "Хранит только последние N сообщений, остальное отбрасывает",
    ),

    /**
     * Стратегия суммаризации — сжимает старые сообщения в краткие резюме через LLM.
     * Последние N сообщений хранятся "как есть", более старые заменяются summary.
     * Хороший баланс между экономией токенов и сохранением контекста.
     */
    SUMMARY(
        displayName = "Summary",
        description = "Сжимает старые сообщения в краткое резюме через LLM",
    ),

    /**
     * Стратегия "липких фактов" — извлекает ключевые факты (цели, решения, предпочтения)
     * в отдельный блок key-value, который обновляется после каждого сообщения пользователя.
     * В запрос отправляется: facts (System message) + последние N сообщений.
     * Факты хранятся в Room (sticky_facts) и переиспользуются между запросами.
     */
    STICKY_FACTS(
        displayName = "Sticky Facts",
        description = "Извлекает ключевые факты (цели, решения, предпочтения) и хранит их отдельно",
    ),

    /**
     * Стратегия ветвления — каждая ветка создаётся как отдельная сессия
     * с копией истории до checkpoint. Контекст строится как sliding window
     * внутри текущей ветки. Основная ценность — UI: создание checkpoint,
     * разветвление и переключение между ветками.
     */
    BRANCHING(
        displayName = "Branching",
        description = "Создание веток диалога с возможностью переключения между ними",
    ),
}
